/**
 * ملف: hero-audio.types.ts
 * الغرض: تعريفات الأنواع (TypeScript Types) الخاصة بوحدة لعبة "خمن
 * البطل من الصوت" فقط. هذا الملف مسؤول فقط عن "شكل" بيانات العنصر،
 * ولا يحتوي أي منطق تنفيذي - بنفس نمط character-guess.types.ts
 * وriddles.types.ts تمامًا.
 */

/**
 * شكل عنصر "خمن البطل من الصوت" الكامل كما يُخزَّن في questions.json
 * وكما يُرجَع في كل استجابات الـ API (random, random-exclude, [id],
 * all) - بنفس أسلوب character-guess.types.ts تمامًا (answer ترجع
 * دائمًا كمصفوفة).
 *
 * - id: رقم صحيح موجب فريد يميّز كل عنصر. **مخزَّن مسبقًا داخل
 *   questions.json نفسه** (نفس أسلوب character-guess.types.ts)، وليس
 *   مولَّدًا تلقائيًا وقت التحميل. عند إضافة أبطال جدد، يجب إعطاء كل
 *   عنصر id فريدًا لم يُستخدم من قبل.
 * - audioUrl: مصفوفة روابط مقاطع صوتية (أصوات/حوارات) خاصة بالبطل،
 *   يختار البوت واحدًا منها عشوائيًا ليشغّله للاعبين قبل التخمين.
 * - answer: مصفوفة كل الإجابات المقبولة لاسم هذا البطل (تشمل الاسم
 *   بالإنجليزية والعربية أو أي صياغات مقبولة أخرى).
 */
export interface HeroAudioQuestion {
  id: number;
  audioUrl: string[];
  answer: string[];
}
