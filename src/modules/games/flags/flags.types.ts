/**
 * ملف: flags.types.ts
 * الغرض: تعريفات الأنواع (TypeScript Types) الخاصة بوحدة لعبة "أعلام"
 * فقط. هذا الملف مسؤول فقط عن "شكل" بيانات عنصر اللعبة، ولا يحتوي أي
 * منطق تنفيذي - بنفس نمط eye.types.ts وriddles.types.ts تمامًا.
 */

/**
 * شكل عنصر "أعلام" الواحد كما يُخزَّن في questions.json وكما يُرجَع في
 * استجابات الـ API.
 *
 * - id: رقم صحيح موجب فريد يميّز كل دولة. **مخزَّن مسبقًا داخل
 *   questions.json نفسه** (نفس أسلوب eye.types.ts وriddles.types.ts)،
 *   مرقّم تسلسليًا (1، 2، 3...) حسب ترتيب العنصر في الملف وقت إنشائه.
 *   عند إضافة عناصر جديدة، يجب إعطاء كل عنصر id فريدًا لم يُستخدم من
 *   قبل (عادة: أكبر id موجود حاليًا + 1). هذا الحقل مهم جدًا لأن بوت
 *   الواتساب يعتمد عليه في نظام منع التكرار (anti-repeat) عبر إرسال
 *   قائمة الـ id المستخدمة سابقًا إلى `random-exclude`.
 * - flag: رابط صورة علم الدولة المعروضة على اللاعب.
 * - emoji: إيموجي علم الدولة (يمكن استخدامه بدلًا من الصورة أو معها في
 *   الرسائل النصية، مثل بوتات الواتساب التي لا تدعم إرسال صور دائمًا).
 * - answers: مصفوفة الإجابات الصحيحة المقبولة لاسم الدولة. دولة واحدة
 *   قد يكون لها أكثر من صياغة مقبولة (مثل "أفغانستان" و"افغانستان"
 *   و"جمهورية أفغانستان الإسلامية")، لذلك هذا الحقل مصفوفة نصوص دائمًا،
 *   وليس نصًا مفردًا - بنفس أسلوب answers في riddles.types.ts وquiz.types.ts.
 */
export interface FlagItem {
  id: number;
  flag: string;
  emoji: string;
  answers: string[];
}
