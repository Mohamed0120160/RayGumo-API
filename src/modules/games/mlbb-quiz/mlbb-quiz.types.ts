/**
 * ملف: mlbb-quiz.types.ts
 * الغرض: تعريفات الأنواع (TypeScript Types) الخاصة بوحدة لعبة "كويز
 * موبايل ليجندز" (MLBB Quiz) فقط. هذا الملف مسؤول فقط عن "شكل" بيانات
 * السؤال، ولا يحتوي أي منطق تنفيذي - بنفس نمط riddles.types.ts
 * وflags.types.ts تمامًا.
 */

/**
 * شكل سؤال "كويز موبايل ليجندز" الواحد كما يُخزَّن في questions.json
 * وكما يُرجَع في استجابات الـ API.
 *
 * - id: رقم صحيح موجب فريد يميّز كل سؤال. **مخزَّن مسبقًا داخل
 *   questions.json نفسه** (نفس أسلوب flags.types.ts وeye.types.ts)،
 *   مرقّم تسلسليًا (1، 2، 3...) حسب ترتيب السؤال في الملف وقت إنشائه.
 *   عند إضافة أسئلة جديدة، يجب إعطاء كل سؤال id فريدًا لم يُستخدم من
 *   قبل (عادة: أكبر id موجود حاليًا + 1). هذا الحقل مهم جدًا لأن بوت
 *   الواتساب يعتمد عليه في نظام منع التكرار (anti-repeat) عبر إرسال
 *   قائمة الـ id المستخدمة سابقًا إلى `random-exclude`.
 * - question: نص السؤال عن لعبة Mobile Legends: Bang Bang (الأبطال،
 *   المراكز، القدرات، إلخ) - يدعم العربية وUTF-8 بالكامل.
 * - answer: نص إجابة واحد يحمل المعلومة الصحيحة (غالبًا مصحوبًا بشرح
 *   إضافي موجز). **نص مفرد (string) وليس مصفوفة**، على عكس answers في
 *   riddles.types.ts وquiz.types.ts - لأن مصدر البيانات الحقيقي هنا لا
 *   يقدّم صياغات بديلة متعددة، بل إجابة شارحة واحدة يُقصد منها مطابقة
 *   المعنى/المضمون عند التحقق، وليس المطابقة الحرفية الدقيقة.
 */
export interface MlbbQuizQuestion {
  id: number;
  question: string;
  answer: string;
}
